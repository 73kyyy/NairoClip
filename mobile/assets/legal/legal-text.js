  /** 取全部文档 id。 */
  function listDocs() { return Object.keys(DOCS); }

  /** 按 id 取文档；不存在返回 null。 */
  function getDoc(id) { return DOCS[id] || null; }

  /**
   * 把文档拍平成可渲染的行列表。
   * 返回：[{ type: 'h'|'p', text, section }]
   * section = 段序号（1 起），用于「条款跳转」定位。
   */
  function flatten(id) {
    const doc = DOCS[id];
    if (!doc) return [];
    const rows = [];
    doc.sections.forEach((sec, i) => {
      rows.push({ type: 'h', text: sec.h, section: i + 1 });
      (sec.ps || []).forEach((p) => rows.push({ type: 'p', text: p, section: i + 1 }));
    });
    return rows;
  }

  /** 文档纯文本（用于复制/分享）。 */
  function toPlainText(id) {
    const doc = DOCS[id];
    if (!doc) return '';
    const lines = [`${doc.title}（更新日期：${doc.updated}）`, ''];
    doc.sections.forEach((sec) => {
      lines.push(sec.h);
      (sec.ps || []).forEach((p) => lines.push(p));
      lines.push('');
    });
    return lines.join('\n');
  }

